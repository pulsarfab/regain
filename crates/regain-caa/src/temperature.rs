pub fn from_adc(adc: u16) -> Option<f64> {
    if !(616..=1020).contains(&adc) {
        return None;
    }
    let r = 10.0 * f64::from(adc) / (1024.0 - f64::from(adc));
    RESISTANCE.windows(2).enumerate().find_map(|(i, pair)| {
        if pair[1] <= r && r <= pair[0] {
            Some(i as f64 - 20.0 + (r - pair[0]) / (pair[1] - pair[0]))
        } else {
            None
        }
    })
}
